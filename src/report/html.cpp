  if (series.x.size() != series.y.size()) {
    throw input_error{"report series x and y must have equal lengths"};
  }
  if (series.x.size() < 2U) {
    return "<p class=\"no-data\">" + localized_content(text.no_data, language) +
           "</p>";
  }

  std::string points;
  for (std::size_t index = 0U; index < series.x.size(); ++index) {
    if (!std::isfinite(series.x[index]) || !std::isfinite(series.y[index])) {
      throw input_error{"report series values must be finite"};
    }
    if (index != 0U) {
      points.push_back(',');
    }
    points += "[" + detail::python_float(series.x[index], "report series") +
              "," + detail::python_float(series.y[index], "report series") +
              "]";
  }

  const std::string chart_id = "fincore-chart-" + std::to_string(chart_index);
  const auto title =
      localized_text(series.title, factor, text_kind::series_title, series.key);
  const auto x_label =
      localized_text(series.x_label, factor, text_kind::axis, series.key);
  const auto y_label =
      localized_text(series.y_label, factor, text_kind::axis, series.key);
  const bool timestamp_axis = factor && standard_series_key(series.key) &&
                              series.x_label == "timestamp";
