std::string escape_html(const std::string_view text) {
    std::string output;
    output.reserve(text.size());
    for (const char character : text) {
        switch (character) {
            case '&':
                output += "&amp;";
                break;
            case '<':
                output += "&lt;";
                break;
            case '>':
                output += "&gt;";
                break;
            case '"':
                output += "&quot;";
                break;
            case '\'':
                output += "&#39;";
                break;
            default:
                output.push_back(character);
                break;
        }
    }
    return output;
}

struct labels {
    std::string notes;
    std::string metadata;
    std::string domain;
    std::string generated;
    std::string no_data;
};

labels labels_for(const std::string& language) {
    if (language == "zh") {
        return {"说明", "元数据", "领域", "由 fincore 生成", "无数据"};
    }
    return {"Notes", "Metadata", "Domain", "Generated by fincore",
            "No data"};
}

void write_cell(std::string& output, const report_cell& cell) {
    switch (cell.type) {
        case report_cell::kind::missing:
            output += "<td class=\"missing\">&mdash;</td>";
            break;
        case report_cell::kind::number:
            output += "<td class=\"numeric\">" +
                      detail::python_float(cell.number, "report cell") +
                      "</td>";
            break;
        case report_cell::kind::text:
            output += "<td>" + escape_html(cell.text) + "</td>";
            break;
        case report_cell::kind::boolean:
            output += std::string("<td>") +
                      (cell.boolean ? "true" : "false") + "</td>";
            break;
    }
}

void write_metric(std::string& output, const report_metric& metric) {
    output += "<div class=\"metric\"><span class=\"metric-label\">" +
              escape_html(metric.label) + "</span><span class=\"metric-value\">";
    if (metric.number.has_value()) {
        output += detail::python_float(*metric.number, "report metric");
    } else if (metric.boolean.has_value()) {
        output += *metric.boolean ? "true" : "false";
    } else if (metric.text.has_value()) {
        output += escape_html(*metric.text);
    } else {
        output += "&mdash;";
    }
    output += "</span>";
    if (!metric.unit.empty()) {
        output += "<span class=\"metric-unit\">" + escape_html(metric.unit) +
                  "</span>";
    }
    output += "</div>\n";
}

std::string svg_series(const report_series& series,
                       const labels& text) {
    if (series.x.size() != series.y.size()) {
        throw input_error{"report series x and y must have equal lengths"};
    }
    if (series.x.size() < 2U) {
        return "<p class=\"no-data\">" + escape_html(text.no_data) + "</p>";
    }
    double minimum_x = std::numeric_limits<double>::infinity();
    double maximum_x = -std::numeric_limits<double>::infinity();
    double minimum_y = std::numeric_limits<double>::infinity();
    double maximum_y = -std::numeric_limits<double>::infinity();
    for (std::size_t index = 0; index < series.x.size(); ++index) {
        if (!std::isfinite(series.x[index]) ||
            !std::isfinite(series.y[index])) {
            throw input_error{"report series values must be finite"};
        }
        minimum_x = std::min(minimum_x, series.x[index]);
        maximum_x = std::max(maximum_x, series.x[index]);
        minimum_y = std::min(minimum_y, series.y[index]);
        maximum_y = std::max(maximum_y, series.y[index]);
    }
    if (maximum_x == minimum_x) {
        minimum_x -= 0.5;
        maximum_x += 0.5;
    }
    if (maximum_y == minimum_y) {
        minimum_y -= 0.5;
        maximum_y += 0.5;
    }
    constexpr double width = 640.0;
    constexpr double height = 240.0;
    constexpr double padding = 32.0;
    std::string points;
    char buffer[64];
    for (std::size_t index = 0; index < series.x.size(); ++index) {
        const double x = padding +
                         (series.x[index] - minimum_x) /
                             (maximum_x - minimum_x) *
                             (width - 2.0 * padding);
        const double y = height - padding -
                         (series.y[index] - minimum_y) /
                             (maximum_y - minimum_y) *
                             (height - 2.0 * padding);
        std::snprintf(buffer, sizeof(buffer), "%.2f,%.2f", x, y);
        if (index != 0U) {
            points.push_back(' ');
        }
        points += buffer;
    }
    std::string output =
        "<figure><figcaption>" + escape_html(series.title) +
        "</figcaption><svg role=\"img\" viewBox=\"0 0 640 240\" "
        "width=\"640\" height=\"240\" xmlns=\"http://www.w3.org/2000/svg\">"
        "<rect x=\"0\" y=\"0\" width=\"640\" height=\"240\" "
        "fill=\"#ffffff\"/><polyline fill=\"none\" stroke=\"#1f6feb\" "
        "stroke-width=\"2\" points=\"" +
        points + "\"/><text x=\"320\" y=\"232\" text-anchor=\"middle\" "
        "font-size=\"12\" fill=\"#444\">" +
        escape_html(series.x_label) +
        "</text><text x=\"12\" y=\"120\" text-anchor=\"middle\" "
        "font-size=\"12\" fill=\"#444\" transform=\"rotate(-90 12 "
        "120)\">" +
        escape_html(series.y_label) + "</text></svg>";
    if (!series.unit.empty()) {
        output += "<p class=\"unit\">" + escape_html(series.unit) + "</p>";
    }
    output += "</figure>\n";
    return output;
}

