bool starts_with(const std::string_view value, const std::string_view prefix) {
  return value.size() >= prefix.size() &&
         value.substr(0U, prefix.size()) == prefix;
}

bool ends_with(const std::string_view value, const std::string_view suffix) {
  return value.size() >= suffix.size() &&
         value.substr(value.size() - suffix.size()) == suffix;
}

bool standard_metric_key(const std::string_view key) {
  return key == "forward_period_count" || key == "observation_count" ||
         key == "finite_factor_count" || key == "coverage_ratio" ||
         key == "quantile_count" ||
         starts_with(key, "mean_information_coefficient.") ||
         starts_with(key, "forward_return_count.");
}

bool standard_series_key(const std::string_view key) {
  return starts_with(key, "ic.") ||
         starts_with(key, "factor_cumulative_returns.");
}

bool standard_table_key(const std::string_view key) {
  return key == "quantile_statistics" || key == "alpha_beta" ||
         key == "mean_returns_by_quantile" ||
         key == "information_coefficient" || key == "information_summary" ||
         key == "returns_summary" || key == "mean_turnover_by_quantile" ||
         key == "turnover_summary" || key == "rank_autocorrelation_summary" ||
         key == "coverage";
}

