std::string escape_html(const std::string_view text) {
  std::string output;
  output.reserve(text.size());
  for (const char character : text) {
    switch (character) {
    case '&':
      output += "&amp;";
      break;
    case '<':
      output += "&lt;";
      break;
    case '>':
      output += "&gt;";
      break;
    case '"':
      output += "&quot;";
      break;
    case '\'':
      output += "&#39;";
      break;
    default:
      output.push_back(character);
      break;
    }
  }
  return output;
}

