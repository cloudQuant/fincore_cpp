std::string render_html(const report_document &document,
                        const report_html_options &options) {
  if (options.language != "en" && options.language != "zh") {
    throw input_error{"unknown report language"};
  }
  switch (options.chart_backend) {
  case report_chart_backend::inline_svg:
  case report_chart_backend::echarts:
    break;
  default:
    throw input_error{"unknown report chart backend"};
  }
  const bool factor = document.domain == "factor";
  const labels text = labels_for(factor);
  const auto title = localized_text(document.title, factor, text_kind::title);
  const auto domain =
      localized_text(document.domain, factor, text_kind::domain);
  std::string output;
  output += "<!doctype html>\n<html lang=\"" + escape_html(options.language) +
            "\">\n<head>\n";
  output += "<meta charset=\"utf-8\">\n<meta name=\"viewport\" "
            "content=\"width=device-width, initial-scale=1\">\n";
  output +=
      "<title id=\"report-document-title\" data-en=\"" +
      escape_html(title.english) + "\" data-zh=\"" +
      escape_html(title.chinese) + "\">" +
      escape_html(options.language == "zh" ? title.chinese : title.english) +
      "</title>\n<style>" + std::string(style_sheet) + "</style>\n";
  if (options.chart_backend == report_chart_backend::echarts) {
    output +=
        "<script>\n" + std::string(detail::echarts_asset()) + "\n</script>\n";
  }
  output +=
      "</head>\n<body class=\"lang-" + escape_html(options.language) + "\">\n";
  output +=
      "<header class=\"hero\"><div class=\"hero-inner\"><div "
      "class=\"hero-copy\">"
      "<div class=\"eyebrow\">" +
      localized_content(text.eyebrow, options.language) +
      "</div><h1 data-en=\"" + escape_html(title.english) + "\" data-zh=\"" +
      escape_html(title.chinese) + "\">" +
      escape_html(options.language == "zh" ? title.chinese : title.english) +
      "</h1><p class=\"subtitle\" data-en=\"" +
      escape_html(text.subtitle.english) + "\" data-zh=\"" +
      escape_html(text.subtitle.chinese) + "\">" +
      escape_html(options.language == "zh" ? text.subtitle.chinese
                                           : text.subtitle.english) +
      "</p><div class=\"chips\">";
  write_metadata_chip(output, "Domain", domain.english, options.language,
                      factor);
  write_metadata_chip(output, "Schema", std::to_string(document.schema_version),
                      options.language, false);
  if (factor) {
    for (const std::string_view key :
         {"asset_count", "date_count", "forward_periods"}) {
      const auto entry = document.metadata.find(std::string{key});
      if (entry != document.metadata.end()) {
        write_metadata_chip(output, key, entry->second, options.language,
                            factor);
      }
    }
  }
  output += "</div></div><div class=\"lang-switch\" aria-label=\"" +
            escape_html(options.language == "zh" ? text.language.chinese
                                                 : text.language.english) +
            "\"><button type=\"button\" data-lang=\"zh\"" +
            std::string{options.language == "zh" ? " class=\"active\"" : ""} +
            " aria-pressed=\"" + (options.language == "zh" ? "true" : "false") +
            "\">中文</button><button type=\"button\" data-lang=\"en\"" +
            std::string{options.language == "en" ? " class=\"active\"" : ""} +
            " aria-pressed=\"" + (options.language == "en" ? "true" : "false") +
            "\">EN</button></div></div></header>\n<main class=\"wrap\">\n";

  std::size_t chart_index = 0U;
  for (const auto &section : document.sections) {
    output += "<section class=\"section\" id=\"" + section_id(section.key) +
              "\" data-key=\"" + escape_html(section.key) +
              "\">\n<div class=\"section-head\"><h2>" +
              localized_content(localized_text(section.title, factor,
                                               text_kind::label,
                                               "section:" + section.key),
                                options.language) +
              "</h2></div>\n";
    if (!section.metrics.empty()) {
      output += "<div class=\"kpi-grid\">\n";
      for (const auto &metric : section.metrics) {
        write_metric(output, metric, options.language, factor);
      }
      output += "</div>\n";
    }
    if (!section.tables.empty() || !section.series.empty()) {
      output += "<div class=\"panel-grid\">\n";
      for (const auto &table : section.tables) {
        write_table(output, table, options.language, factor);
      }
      for (const auto &series : section.series) {
        if (options.chart_backend == report_chart_backend::echarts) {
          output += echarts_series(series, chart_index, text, options.language,
                                   factor);
        } else {
          output += svg_series(series, text, options.language, factor);
        }
        ++chart_index;
      }
      output += "</div>\n";
    }
    if (!section.notes.empty()) {
      output += "<div class=\"notes\"><strong>" +
                localized_content(text.notes, options.language) +
                "</strong><ul>";
      for (const auto &note : section.notes) {
        output +=
            "<li>" +
            localized_content(localized_text(note, factor, text_kind::note),
                              options.language) +
            "</li>";
      }
      output += "</ul></div>\n";
    }
    output += "</section>\n";
  }
  if (!document.metadata.empty()) {
    output += "<section class=\"section\" id=\"metadata\"><div "
              "class=\"section-head\"><h2>" +
              localized_content(text.metadata, options.language) +
              "</h2></div><article class=\"card table-card\"><dl "
              "class=\"metadata-list\">";
    for (const auto &entry : document.metadata) {
      output += "<dt>" +
                localized_content(localized_text(entry.first, factor,
                                                 text_kind::metadata_key),
                                  options.language) +
                "</dt><dd>" + escape_html(entry.second) + "</dd>";
    }
    output += "</dl></article></section>\n";
  }
  output +=
      "<footer class=\"report-footer\">" +
      localized_content(text.generated, options.language) + " &middot; " +
      localized_content(
          localized_text("Schema", factor, text_kind::metadata_key),
          options.language) +
      " " + std::to_string(document.schema_version) +
      "</footer>\n</main>\n<script>\n"
      "function setFincoreLanguage(language){var "
      "active=language===\"en\"?\"en\":\"zh\";"
      "document.documentElement.lang=active;document.body.classList.remove("
      "\"lang-en\",\"lang-zh\");"
      "document.body.classList.add(\"lang-\"+active);"
      "document.querySelectorAll(\"[data-en][data-zh]\").forEach(function("
      "element){element.textContent=element.dataset[active];});"
      "var "
      "title=document.getElementById(\"report-document-title\");if(title){"
      "document.title=title.dataset[active];}"
      "document.querySelectorAll(\".lang-switch "
      "button\").forEach(function(button){var "
      "selected=button.dataset.lang===active;"
      "button.classList.toggle(\"active\",selected);button.setAttribute(\"aria-"
      "pressed\",selected?\"true\":\"false\");});"
      "(window.__fincoreReportCharts||[]).forEach(function(entry){entry.chart."
      "setOption(entry.options[active],true);"
      "entry.element.setAttribute(\"aria-label\",entry.element.getAttribute("
      "\"data-chart-label-\"+active));});}"
      "document.querySelectorAll(\".lang-switch "
      "button\").forEach(function(button){button.addEventListener(\"click\","
      "function(){setFincoreLanguage(button.dataset.lang);});});"
      "window.addEventListener(\"resize\",function(){(window.__"
      "fincoreReportCharts||[]).forEach(function(entry){entry.chart.resize();})"
      ";});"
      "setFincoreLanguage(" +
      script_safe_json_string(options.language) +
      ");\n</script>\n</body>\n</html>\n";
  return output;
}

