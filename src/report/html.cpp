std::string localized_content(const text_pair &text,
                              const std::string &language) {
  if (text.english == text.chinese) {
    return escape_html(text.english);
  }
  return "<span data-en=\"" + escape_html(text.english) + "\" data-zh=\"" +
         escape_html(text.chinese) + "\">" +
         escape_html(language == "zh" ? text.chinese : text.english) +
         "</span>";
}

std::string format_fixed(const double value, const int precision) {
  std::ostringstream formatted;
  formatted << std::fixed << std::setprecision(precision) << value;
  return formatted.str();
}

std::string format_significant(const double value, const int precision) {
  std::ostringstream formatted;
  formatted << std::setprecision(precision) << value;
  return formatted.str();
}

std::string format_count(const double value) {
  std::string digits = format_fixed(value, 0);
  const std::size_t first_digit =
      !digits.empty() && digits.front() == '-' ? 1U : 0U;
  for (std::size_t index = digits.size(); index > first_digit + 3U;
       index -= 3U) {
    digits.insert(index - 3U, 1U, ',');
  }
  return digits;
}

std::string metric_value(const report_metric &metric, const bool factor) {
  if (metric.number.has_value()) {
    if (!std::isfinite(*metric.number)) {
      return detail::python_float(*metric.number, "report metric");
    }
    if (factor && (metric.unit == "count" || metric.unit == "rows")) {
      return format_count(*metric.number);
    }
    if (factor && metric.key == "coverage_ratio") {
      return format_fixed(*metric.number * 100.0, 1) + "%";
    }
    if (factor && metric.unit == "correlation") {
      return format_fixed(*metric.number, 4);
    }
    if (factor) {
      return format_fixed(*metric.number, 4);
    }
    return detail::python_float(*metric.number, "report metric");
  }
  if (metric.boolean.has_value()) {
    return *metric.boolean ? "true" : "false";
  }
  if (metric.text.has_value()) {
    return escape_html(*metric.text);
  }
  return "&mdash;";
}

void write_cell(std::string &output, const report_cell &cell,
                const std::string &language, const bool factor,
                const std::string_view table_key,
                const std::string_view column) {
  switch (cell.type) {
  case report_cell::kind::missing:
    output += "<td class=\"missing\">&mdash;</td>";
    break;
  case report_cell::kind::number:
    if (factor && standard_table_key(table_key) && column != "date" &&
        column != "period") {
      if (!std::isfinite(cell.number)) {
        output += "<td class=\"numeric\">" +
                  detail::python_float(cell.number, "report cell") + "</td>";
      } else if (column == "count" || ends_with(column, "_count")) {
        output +=
            "<td class=\"numeric\">" + format_count(cell.number) + "</td>";
      } else {
        output += "<td class=\"numeric\">" +
                  format_significant(cell.number, 6) + "</td>";
      }
    } else {
      output += "<td class=\"numeric\">" +
                detail::python_float(cell.number, "report cell") + "</td>";
    }
    break;
  case report_cell::kind::text:
    output += "<td>" +
              localized_content(
                  localized_text(cell.text, factor, text_kind::row, table_key),
                  language) +
              "</td>";
    break;
  case report_cell::kind::boolean:
    output += std::string{"<td>"} + (cell.boolean ? "true" : "false") + "</td>";
    break;
  }
}

void write_metric(std::string &output, const report_metric &metric,
                  const std::string &language, const bool factor) {
  output +=
      "<article class=\"kpi\"><span class=\"kpi-label\">" +
      localized_content(localized_text(metric.label, factor, text_kind::label,
                                       "metric:" + metric.key),
                        language) +
      "</span><span class=\"kpi-value\">" +
      metric_value(metric, factor && standard_metric_key(metric.key)) +
      "</span>";
  if (!metric.unit.empty() && metric.key != "coverage_ratio") {
    output +=
        "<span class=\"kpi-unit\">" +
        localized_content(localized_text(metric.unit, factor, text_kind::unit,
                                         "metric:" + metric.key),
                          language) +
        "</span>";
  }
  output += "</article>\n";
}

std::string svg_series(const report_series &series, const labels &text,
                       const std::string &language, const bool factor) {
  if (series.x.size() != series.y.size()) {
    throw input_error{"report series x and y must have equal lengths"};
  }
  if (series.x.size() < 2U) {
    return "<p class=\"no-data\">" + localized_content(text.no_data, language) +
           "</p>";
  }
  double minimum_x = std::numeric_limits<double>::infinity();
  double maximum_x = -std::numeric_limits<double>::infinity();
  double minimum_y = std::numeric_limits<double>::infinity();
  double maximum_y = -std::numeric_limits<double>::infinity();
  for (std::size_t index = 0; index < series.x.size(); ++index) {
    if (!std::isfinite(series.x[index]) || !std::isfinite(series.y[index])) {
      throw input_error{"report series values must be finite"};
    }
    minimum_x = std::min(minimum_x, series.x[index]);
    maximum_x = std::max(maximum_x, series.x[index]);
    minimum_y = std::min(minimum_y, series.y[index]);
    maximum_y = std::max(maximum_y, series.y[index]);
  }
  if (maximum_x == minimum_x) {
    minimum_x -= 0.5;
    maximum_x += 0.5;
  }
  if (maximum_y == minimum_y) {
    minimum_y -= 0.5;
    maximum_y += 0.5;
  }
  constexpr double width = 640.0;
  constexpr double height = 240.0;
  constexpr double padding = 32.0;
  std::string points;
  char buffer[64];
  for (std::size_t index = 0; index < series.x.size(); ++index) {
    const double x = padding + (series.x[index] - minimum_x) /
                                   (maximum_x - minimum_x) *
                                   (width - 2.0 * padding);
    const double y = height - padding -
                     (series.y[index] - minimum_y) / (maximum_y - minimum_y) *
                         (height - 2.0 * padding);
    std::snprintf(buffer, sizeof(buffer), "%.2f,%.2f", x, y);
    if (index != 0U) {
      points.push_back(' ');
    }
    points += buffer;
  }
  const auto title =
      localized_text(series.title, factor, text_kind::series_title, series.key);
  const auto x_label =
      localized_text(series.x_label, factor, text_kind::axis, series.key);
  const auto y_label =
      localized_text(series.y_label, factor, text_kind::axis, series.key);
  std::string output =
      "<article class=\"card chart-card\"><h3>" +
      localized_content(title, language) +
      "</h3><svg role=\"img\" viewBox=\"0 0 640 240\" width=\"640\" "
      "height=\"240\" xmlns=\"http://www.w3.org/2000/svg\"><rect x=\"0\" "
      "y=\"0\" width=\"640\" height=\"240\" fill=\"#ffffff\"/>"
      "<polyline fill=\"none\" stroke=\"#0e7490\" stroke-width=\"2\" "
      "points=\"" +
      points +
      "\"/><text x=\"320\" y=\"232\" text-anchor=\"middle\" "
      "font-size=\"12\" fill=\"#475569\" data-en=\"" +
      escape_html(x_label.english) + "\" data-zh=\"" +
      escape_html(x_label.chinese) + "\">" +
      escape_html(language == "zh" ? x_label.chinese : x_label.english) +
      "</text><text x=\"12\" y=\"120\" text-anchor=\"middle\" "
      "font-size=\"12\" fill=\"#475569\" transform=\"rotate(-90 12 "
      "120)\" data-en=\"" +
      escape_html(y_label.english) + "\" data-zh=\"" +
      escape_html(y_label.chinese) + "\">" +
      escape_html(language == "zh" ? y_label.chinese : y_label.english) +
      "</text></svg>";
  if (!series.unit.empty()) {
    output +=
        "<p class=\"unit\">" +
        localized_content(localized_text(series.unit, factor, text_kind::unit,
                                         "series:" + series.key),
                          language) +
        "</p>";
  }
  output += "</article>\n";
  return output;
}

std::string script_safe_json_string(const std::string_view value) {
  std::string json;
  detail::append_json_string(json, value);
  std::string safe;
  safe.reserve(json.size());
  for (const char character : json) {
    switch (character) {
    case '<':
      safe += "\\u003c";
      break;
    case '>':
      safe += "\\u003e";
      break;
    case '&':
      safe += "\\u0026";
      break;
    default:
      safe.push_back(character);
      break;
    }
  }
  return safe;
}

