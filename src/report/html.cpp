void write_table(std::string &output, const report_table &table,
                 const std::string &language, const bool factor) {
  output +=
      "<article class=\"card table-card\"><h3>" +
      localized_content(localized_text(table.title, factor, text_kind::label,
                                       "table:" + table.key),
                        language) +
      "</h3><div class=\"table-wrap\"><table class=\"data-table\"><thead><tr>";
  for (const auto &column : table.columns) {
    output += "<th>" +
              localized_content(
                  localized_text(column, factor, text_kind::column, table.key),
                  language) +
              "</th>";
  }
  output += "</tr></thead><tbody>\n";
  for (const auto &row : table.rows) {
    if (row.size() != table.columns.size()) {
      throw input_error{"report table rows must match the column count"};
    }
    output += "<tr>";
    for (std::size_t column_index = 0U; column_index < row.size();
         ++column_index) {
      write_cell(output, row[column_index], language, factor, table.key,
                 table.columns[column_index]);
    }
    output += "</tr>\n";
  }
  output += "</tbody></table></div></article>\n";
}

void write_metadata_chip(std::string &output, const std::string_view key,
                         const std::string_view value,
                         const std::string &language, const bool factor) {
  output +=
      "<span class=\"chip\"><b>" +
      localized_content(localized_text(key, factor, text_kind::metadata_key),
                        language) +
      "</b><span>" +
      localized_content(localized_text(value, factor,
                                       key == "Domain"
                                           ? text_kind::domain
                                           : text_kind::metadata_key),
                        language) +
      "</span></span>";
}

