std::string render_html(const report_document& document,
                        const report_html_options& options) {
    const labels text = labels_for(options.language);
    std::string output;
    output += "<!doctype html>\n<html lang=\"" +
              escape_html(options.language) + "\">\n<head>\n";
    output += "<meta charset=\"utf-8\">\n<meta name=\"viewport\" "
              "content=\"width=device-width, initial-scale=1\">\n";
    output += "<title>" + escape_html(document.title) + "</title>\n<style>" +
              std::string(style_sheet) + "</style>\n</head>\n<body>\n";
    output += "<header><h1>" + escape_html(document.title) + "</h1>";
    output += "<p class=\"domain\">" + escape_html(text.domain) + ": " +
              escape_html(document.domain) + "</p></header>\n<main>\n";
    for (const auto& section : document.sections) {
        output += "<section id=\"section-" + escape_html(section.key) +
                  "\" data-key=\"" + escape_html(section.key) + "\">\n";
        output += "<h2>" + escape_html(section.title) + "</h2>\n";
        if (!section.metrics.empty()) {
            output += "<div class=\"metrics\">\n";
            for (const auto& metric : section.metrics) {
                write_metric(output, metric);
            }
            output += "</div>\n";
        }
        for (const auto& table : section.tables) {
            output += "<table><caption>" + escape_html(table.title) +
                      "</caption><thead><tr>";
            for (const auto& column : table.columns) {
                output += "<th>" + escape_html(column) + "</th>";
            }
            output += "</tr></thead><tbody>\n";
            for (const auto& row : table.rows) {
                if (row.size() != table.columns.size()) {
                    throw input_error{
                        "report table rows must match the column count"};
                }
                output += "<tr>";
                for (const auto& cell : row) {
                    write_cell(output, cell);
                }
                output += "</tr>\n";
            }
            output += "</tbody></table>\n";
        }
        for (const auto& series : section.series) {
            output += svg_series(series, text);
        }
        if (!section.notes.empty()) {
            output += "<div class=\"notes\"><strong>" +
                      escape_html(text.notes) + "</strong><ul>";
            for (const auto& note : section.notes) {
                output += "<li>" + escape_html(note) + "</li>";
            }
            output += "</ul></div>\n";
        }
        output += "</section>\n";
    }
    if (!document.metadata.empty()) {
        output += "<section id=\"metadata\"><h2>" +
                  escape_html(text.metadata) + "</h2><dl>";
        for (const auto& entry : document.metadata) {
            output += "<dt>" + escape_html(entry.first) + "</dt><dd>" +
                      escape_html(entry.second) + "</dd>";
        }
        output += "</dl></section>\n";
    }
    output += "</main>\n<footer>" + escape_html(text.generated) +
              " &middot; schema " + std::to_string(document.schema_version) +
              "</footer>\n</body>\n</html>\n";
    return output;
}

