namespace {

constexpr fincore::timestamp day = 86'400'000'000'000LL;

fincore::chart_series monthly_series(const std::size_t count) {
    fincore::chart_series series;
    series.label = "Series";
    for (std::size_t position = 0U; position < count; ++position) {
        series.index.push_back(fincore::utc_timestamp(2021, 1, 1) +
                               static_cast<fincore::timestamp>(position) *
                                   day);
        series.values.push_back(0.1);
    }
    return series;
}

std::string read_file(const std::filesystem::path& path) {
    std::ifstream stream(path, std::ios::binary);
    return std::string(std::istreambuf_iterator<char>(stream),
                       std::istreambuf_iterator<char>());
}

std::size_t count_occurrences(const std::string& text,
                              const std::string& needle) {
    std::size_t count = 0U;
    std::size_t position = text.find(needle);
    while (position != std::string::npos) {
        ++count;
        position = text.find(needle, position + needle.size());
    }
    return count;
}

}  // namespace

TEST(HtmlReportBuilder, EscapesTitlesHeadingsAndKeys) {
    fincore::html_report_builder builder;
    builder.add_title("<b>A&B</b>");
    builder.add_heading("O'Reilly \"Q\"", 2);
    const std::string html = builder.build();
    EXPECT_NE(html.find("<h1>&lt;b&gt;A&amp;B&lt;/b&gt;</h1>"),
              std::string::npos);
    EXPECT_NE(html.find("<h2>O&#x27;Reilly &quot;Q&quot;</h2>"),
              std::string::npos);
}

TEST(HtmlReportBuilder, BuildIsSelfContainedWithStableCss) {
    fincore::html_report_builder builder;
    builder.add_title("Report");
    const std::string html = builder.build();
    EXPECT_EQ(html.rfind("<!DOCTYPE html>\n<html><head><meta "
                         "charset='utf-8'>",
                         0),
              0U);
    EXPECT_NE(html.find("<title>Performance Report</title>"),
              std::string::npos);
    EXPECT_NE(html.find("<style>"), std::string::npos);
    EXPECT_NE(html.find("</style>"), std::string::npos);
    EXPECT_NE(html.find("<div class=\"footer\">Generated by "
                        "<strong>fincore</strong></div>"),
              std::string::npos);
    EXPECT_EQ(html.find("<script"), std::string::npos);
    EXPECT_EQ(html.find("<link"), std::string::npos);
    EXPECT_EQ(html.find("http://"), std::string::npos);
    EXPECT_EQ(html.find("https://"), std::string::npos);

    const std::string_view css = fincore::html_report_builder::css();
    EXPECT_EQ(css.rfind("<style>", 0), 0U);
    EXPECT_EQ(css.substr(css.size() - 9U), "</style>\n");
    EXPECT_NE(css.find(".metric-card"), std::string::npos);
    EXPECT_NE(css.find(".positive"), std::string::npos);
}

TEST(HtmlReportBuilder, StatsTableFormatsValuesAndMissingness) {
    std::vector<fincore::html_metric> stats{
        fincore::html_metric::number_metric("sharpe", 0.12345),
        fincore::html_metric::number_metric("loss", -0.5),
        fincore::html_metric::number_metric("flat", 0.0),
        fincore::html_metric::text_metric("state", "ok"),
        fincore::html_metric::missing("<missing>")};
    fincore::html_report_builder builder;
    builder.add_stats_table(stats);
    const std::string html = builder.build();

    EXPECT_NE(html.find(
                  "<tr><th>sharpe</th><td class=\"positive\">0.1235</td></tr>"),
              std::string::npos);
    EXPECT_NE(html.find(
                  "<tr><th>loss</th><td class=\"negative\">-0.5000</td></tr>"),
              std::string::npos);
    EXPECT_NE(html.find("<tr><th>flat</th><td class=\"\">0.0000</td></tr>"),
              std::string::npos);
    EXPECT_NE(html.find("<tr><th>state</th><td class=\"\">ok</td></tr>"),
              std::string::npos);
    EXPECT_NE(html.find("<tr><th>&lt;missing&gt;</th><td "
                        "class=\"\">nan</td></tr>"),
              std::string::npos);
}

TEST(HtmlReportBuilder, MetricCardsSelectKeysAndRenderNA) {
    std::vector<fincore::html_metric> stats{
        fincore::html_metric::number_metric("sharpe", 0.12345),
        fincore::html_metric::number_metric("loss", -0.5),
        fincore::html_metric::text_metric("state", "ok")};
    fincore::html_report_builder builder;
    builder.add_metric_cards(stats, {"sharpe", "state", "absent"});
    const std::string html = builder.build();
    EXPECT_NE(html.find("<div class=\"value positive\">0.1235</div>"),
              std::string::npos);
    EXPECT_NE(html.find("<div class=\"label\">sharpe</div>"),
              std::string::npos);
    EXPECT_NE(html.find("<div class=\"label\">state</div>"),
              std::string::npos);
    EXPECT_NE(html.find("<div class=\"label\">absent</div>"),
              std::string::npos);
    // "state" is a text metric, so its card has no number, and "absent" matches
    // no metric at all: both fall back to the same marker.
    EXPECT_EQ(count_occurrences(html, ">N/A<"), 2U);
    // The selected "loss" key is not rendered when explicit keys are given.
    EXPECT_EQ(html.find("loss"), std::string::npos);

    fincore::html_report_builder all;
    all.add_metric_cards(stats);
    const std::string all_html = all.build();
    EXPECT_NE(all_html.find("<div class=\"label\">loss</div>"),
              std::string::npos);
    EXPECT_NE(all_html.find("<div class=\"value negative\">-0.5000</div>"),
              std::string::npos);
    EXPECT_EQ(count_occurrences(all_html, "<div class=\"metric-card\">"), 3U);
}

TEST(HtmlReportBuilder, SeriesTablesTruncateToHeadAndTail) {
    fincore::html_report_builder builder;
    builder.plot_returns(monthly_series(25U));
    const std::string html = builder.build();
    EXPECT_NE(html.find("<h2>Cumulative Returns</h2>"), std::string::npos);
    // 21 is the header row plus the 20 retained data rows: ten from the head and
    // ten from the tail, with no marker row standing in for the dropped middle.
    EXPECT_EQ(count_occurrences(html, "<tr>"), 21U);
    EXPECT_NE(html.find("2021-01-01"), std::string::npos);
    EXPECT_NE(html.find("2021-01-25"), std::string::npos);
    EXPECT_EQ(html.find("2021-01-13"), std::string::npos);
    EXPECT_NE(html.find("<td>0.100000</td>"), std::string::npos);
}

TEST(HtmlReportBuilder, DrawdownAndRollingSharpeSections) {
    const auto benchmark = monthly_series(3U);
    fincore::html_report_builder builder;
    builder.plot_drawdown(monthly_series(3U));
    builder.plot_rolling_sharpe(monthly_series(3U), &benchmark, 126U);
    const std::string html = builder.build();
    EXPECT_NE(html.find("<h2>Drawdown</h2>"), std::string::npos);
    EXPECT_NE(html.find("<h2>Rolling Sharpe Ratio (126-day window)</h2>"),
              std::string::npos);
    EXPECT_NE(html.find("<h3>Benchmark Rolling Sharpe Ratio</h3>"),
              std::string::npos);
    EXPECT_EQ(count_occurrences(html, "<th>Sharpe</th>"), 2U);
}

TEST(HtmlReportBuilder, MonthlyHeatmapPaintsPercentCellsAndMissingRows) {
    fincore::heat_grid grid;
    grid.years = {2021};
    grid.columns.assign(std::begin(fincore::month_labels),
                        std::end(fincore::month_labels));
    grid.values.assign(12U, 0.0);
    grid.present.assign(12U, true);
    grid.values[0] = 0.560685325129362;
    grid.present[1] = false;
    grid.values[1] = std::numeric_limits<double>::quiet_NaN();

    fincore::html_report_builder builder;
    builder.plot_monthly_heatmap(grid);
    const std::string html = builder.build();
    EXPECT_NE(html.find("<h2>Monthly Returns</h2>"), std::string::npos);
    EXPECT_NE(html.find("<table class=\"dataframe monthly\">"),
              std::string::npos);
    EXPECT_NE(html.find("<th>Jan</th>"), std::string::npos);
    EXPECT_NE(html.find("<tr><th>2021</th><td>0.56%</td><td>NaN</td>"),
              std::string::npos);
    EXPECT_EQ(count_occurrences(html, "NaN"), 1U);
}

TEST(HtmlReportBuilder, SaveWritesBuildBytesAndRejectsEmptyPath) {
    fincore::html_report_builder builder;
    builder.add_title("Saved <Report>");
    const auto path =
        std::filesystem::temp_directory_path() / "fincore_html_builder.html";
    std::filesystem::remove(path);
    builder.save(path.string());
    EXPECT_EQ(read_file(path), builder.build());
    EXPECT_THROW(builder.save(""), fincore::input_error);
    std::filesystem::remove(path);
}
